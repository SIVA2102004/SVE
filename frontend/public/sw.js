// SVE Auto-Update Service Worker
// Automatically cleans old caches and activates instantly
const CACHE_NAME = 'sve-cache-v3';

self.addEventListener('install', (event) => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((cacheNames) => {
      return Promise.all(
        cacheNames.map((cache) => {
          return caches.delete(cache);
        })
      );
    }).then(() => self.clients.claim())
  );
});

// Cache assets on first load, network fallback
self.addEventListener('fetch', (event) => {
  // Ignore non-GET requests (e.g. POST, PUT, DELETE for API)
  if (event.request.method !== 'GET') return;

  const url = new URL(event.request.url);

  // If request is to API server or WebSocket, let the browser handle it directly
  if (url.origin.includes('onrender.com') || url.pathname.startsWith('/api')) {
    return;
  }

  // Always fetch latest HTML navigation from server; fallback to cache if offline
  if (event.request.mode === 'navigate') {
    event.respondWith(
      fetch(event.request)
        .then((response) => {
          if (response && response.status === 200) {
            const clone = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
          }
          return response;
        })
        .catch(() => {
          return caches.match(event.request).then((cached) => {
            return cached || caches.match('/index.html');
          });
        })
    );
    return;
  }

  // Static assets (CSS, JS, images): Stale-while-revalidate
  event.respondWith(
    caches.match(event.request).then((cachedResponse) => {
      const fetchPromise = fetch(event.request)
        .then((networkResponse) => {
          if (networkResponse && networkResponse.status === 200) {
            const clone = networkResponse.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
          }
          return networkResponse;
        })
        .catch(() => cachedResponse);

      return cachedResponse || fetchPromise;
    })
  );
});
